/**
 * Prediction mechanic core logic (18_tutoriales_v3.md §5) — "the pedagogical piece that matters
 * more than any other improvement in this package." Pure functions only; the UI lives in
 * PredictionStrip.tsx, the wiring into a simulated round lives in App.tsx.
 */
import type { Indicators } from '../../types';
import { predictionSkill, type PredictionSkill } from '../../sim/v2/research';
import bandsJson from './predictionBands.json';

export type PredictionDirection = 'down' | 'flat' | 'up';

// Fixed to exactly the three indicators the source spec's own mockup shows (§5), regardless of
// level — economicSecurity is tracked internally from level 1 even though its dashboard card only
// appears from level 2 onward (Dashboard.tsx), so predicting it early is still meaningful.
export const PREDICTED_INDICATORS = ['biodiversity', 'co2EqEmissionsPerCapita', 'economicSecurity'] as const;
export type PredictedIndicatorKey = typeof PREDICTED_INDICATORS[number];

export type PredictionSelections = Partial<Record<PredictedIndicatorKey, PredictionDirection>>;

export interface PredictionResult {
  indicator: PredictedIndicatorKey;
  predicted: PredictionDirection;
  actual: PredictionDirection;
  delta: number;
  correct: boolean;
  /** Level whose band classified the change (phase 48). */
  level: number;
  /** "No change" band used: |Δ| < band reads as flat (phase 48). */
  band: number;
  /** Persistence baseline: the actual direction of the previous year for this indicator ('flat' in a level's first year). */
  persistencePred: PredictionDirection;
}

/**
 * v6 / phase 48 (mejora-general/files/48 §1): the "no change" band of each indicator and level is the 33rd percentile of
 * |ΔX| per year among the harness's synthetic players (scripts/harness/randomPlayers.ts), so a priori "no change" happens
 * a third of the time. Generated by `npx tsx scripts/prediction-bands.ts` (which refuses a JSON whose modelVersion is not
 * MODEL_VERSION); `climatology` holds the down/flat/up proportions it measured, the climatology baseline of the skill
 * score. Replaces the 1.1 band (1 % of a fixed RANGE, FLAT_THRESHOLD_FRACTION), which made "no change" right 55–63 % of
 * the years with model 2.0.
 */
export interface PredictionBandsFile {
  modelVersion: string;
  bands: Record<string, Record<PredictedIndicatorKey, number>>;
  climatology: Record<string, Record<PredictedIndicatorKey, Record<PredictionDirection, number>>>;
}
export const PREDICTION_BANDS = bandsJson as PredictionBandsFile;

/** Levels without their own band (Territorio would use level 2, spec §7) fall back to level 2. */
const levelKey = (level: number): string => (PREDICTION_BANDS.bands[String(level)] ? String(level) : '2');

export function predictionBand(key: PredictedIndicatorKey, level: number): number {
  return PREDICTION_BANDS.bands[levelKey(level)][key];
}

export function climatologyOf(key: PredictedIndicatorKey, level: number): Record<PredictionDirection, number> {
  return PREDICTION_BANDS.climatology[levelKey(level)][key];
}

export function actualDirection(key: PredictedIndicatorKey, before: number, after: number, level: number): PredictionDirection {
  const delta = after - before;
  if (Math.abs(delta) < predictionBand(key, level)) return 'flat';
  return delta > 0 ? 'up' : 'down';
}

/** Actual direction of every predicted indicator over one year (the next year's persistence baseline). */
export function directionsOf(before: Indicators, after: Indicators, level: number): Record<PredictedIndicatorKey, PredictionDirection> {
  const out = {} as Record<PredictedIndicatorKey, PredictionDirection>;
  PREDICTED_INDICATORS.forEach((key) => { out[key] = actualDirection(key, before[key], after[key], level); });
  return out;
}

/**
 * Only evaluates indicators the player actually predicted — predicting is per-indicator optional. `persistence`: the
 * actual directions of the previous year of the same level (omitted in a level's first year: the baseline is 'flat').
 */
export function evaluatePredictions(
  selections: PredictionSelections, before: Indicators, after: Indicators, level: number,
  persistence?: Partial<Record<PredictedIndicatorKey, PredictionDirection>> | null,
): PredictionResult[] {
  return PREDICTED_INDICATORS
    .filter((key) => selections[key] !== undefined)
    .map((key) => {
      const predicted = selections[key]!;
      const delta = after[key] - before[key];
      const actual = actualDirection(key, before[key], after[key], level);
      return {
        indicator: key, predicted, actual, delta, correct: predicted === actual,
        level, band: predictionBand(key, level), persistencePred: persistence?.[key] ?? 'flat',
      };
    });
}

/** Prediction skill of a session against the persistence and climatology baselines (§2). */
export function sessionPredictionSkill(results: PredictionResult[]): PredictionSkill {
  return predictionSkill(results.map((r) => ({
    predicted: r.predicted, actual: r.actual, persistence: r.persistencePred, climatology: climatologyOf(r.indicator, r.level),
  })));
}

const ENABLED_KEY = 'decarbonation.prediction.enabled';

export function loadPredictionEnabled(): boolean {
  try {
    const raw = localStorage.getItem(ENABLED_KEY);
    return raw === null ? true : raw === 'true'; // opt-out, on by default per §5
  } catch { return true; }
}

export function savePredictionEnabled(enabled: boolean): void {
  try { localStorage.setItem(ENABLED_KEY, String(enabled)); } catch { /* ignore */ }
}
